import assert from 'node:assert/strict';
import {inspectUsageSegments as inspect} from './lib/app-server-usage-segments.mjs';
const counts={inputTokens:10,cachedInputTokens:3,outputTokens:4,reasoningOutputTokens:2,totalTokens:14};
const event={method:'thread/tokenUsage/updated',params:{threadId:'private-thread',turnId:'private-turn',tokenUsage:{last:counts,total:counts}}};
const ids={threadId:'private-thread',turnId:'private-turn'};
let result=inspect([[event],[event,event]],ids);
assert.equal(result.status,'SNAPSHOT_UNVERIFIED_SOURCE');
assert.equal(result.sameValueObservations,3);
assert.equal(result.uniqueness,'UNKNOWN');
assert.equal(result.total.inputTokens,10);
assert.doesNotMatch(JSON.stringify(result),/private-thread|private-turn/);
assert.equal(inspect([[],[]],ids).status,'NO_USAGE');
assert.equal(inspect([[event],[{...event,params:{...event.params,tokenUsage:{last:{...counts,inputTokens:11},total:counts}}}]],ids).status,'MULTIPLE_DISTINCT_SNAPSHOTS_UNRESOLVED');
assert.equal(inspect([[event],[{...event,params:{...event.params,turnId:'different'}}]],ids).status,'ID_MISMATCH');
assert.equal(inspect([[event],null],ids).status,'INVALID_SEGMENTS');
assert.equal(inspect([[event],[{method:'irrelevant'}]],ids).sameValueObservations,1);
assert.deepEqual(inspect(Array.from({length:101},()=>[]),ids),{status:'SEGMENT_LIMIT_EXCEEDED'});
assert.deepEqual(inspect([[event,...Array.from({length:10000},()=>({method:'irrelevant'}))]],ids),{status:'EVENT_LIMIT_EXCEEDED'});
console.log('PASS: segmented synthetic usage duplicates, conflicts, and identity guards');
