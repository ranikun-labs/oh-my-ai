import assert from 'node:assert/strict';
import { jiraObservations } from './lib/jira-observations.mjs';
import { formatWorkTree } from './lib/work-tree-view.mjs';
const ts='2026-11-18T00:00:00Z';
const issues=[{key:'RPL-1',fields:{summary:'목표',status:{name:'진행 중'}}},{key:'RPL-2',fields:{parent:{key:'RPL-1'},issuelinks:[{id:'2',type:{name:'Blocks'},outwardIssue:{key:'RPL-1'}}]}}];
const x=jiraObservations(issues,ts);
assert.equal(x.coverage,'partial');
assert.match(formatWorkTree({items:x.items,relations:x.relations}),/RPL-1 \| parent \| RPL-2/);
assert.match(formatWorkTree({items:x.items,relations:x.relations}),/RPL-2 \| blocks \| RPL-1/);
assert.equal(x.items[0].status,'진행 중');
assert.throws(()=>jiraObservations(issues, 'x'.repeat(1001)));
assert.throws(()=>jiraObservations([{key:'RPL-1',fields:{issuelinks:[null]}}],ts));
assert.throws(()=>jiraObservations([{key:'RPL-1',fields:{issuelinks:[{type:{name:'Blocks'},inwardIssue:{key:'RPL-2'},outwardIssue:{key:'RPL-2'}}]}}],ts));
assert.throws(()=>jiraObservations([{key:'RPL-1',fields:{parent:{key:'RPL-1'}}}],ts));
for (const parent of [{}, [], 'bad', {key:'bad'}, {key:`RPL-${'1'.repeat(101)}`}]) assert.throws(()=>jiraObservations([{key:'RPL-1',fields:{parent}}],ts),/invalid parent/);
assert.equal(jiraObservations([{key:'RPL-1',fields:{parent:null}}],ts).coverage,'partial');
assert.deepEqual(jiraObservations([{key:'RPL-1',fields:{parent:{key:'RPL-2'}}}],ts).relations,[]);
const external=jiraObservations([{key:'RPL-1',fields:{parent:{key:'RPL-2'},issuelinks:[{type:{name:'Blocks'},outwardIssue:{key:'RPL-3'}}]}}],ts);
assert.equal(external.omitted_relation_observations,2);
assert.equal(external.relations.length,0);
const unsupported=jiraObservations([{key:'RPL-1',fields:{issuelinks:[{type:{name:'Duplicate'},outwardIssue:{key:'RPL-2'}}]}}],ts);
assert.equal(unsupported.unsupported_link_observations,1);
assert.equal(unsupported.omitted_relation_observations,0);
assert.equal(unsupported.relations.length,0);
const many=Array.from({length:2000},()=>({type:{name:'Blocks'},outwardIssue:{key:'RPL-2'}}));
assert.throws(()=>jiraObservations([{key:'RPL-1',fields:{issuelinks:many}},{key:'RPL-2',fields:{parent:{key:'RPL-1'}}}],ts),/too many relations/);
assert.throws(()=>jiraObservations([{key:'RPL-1',fields:{issuelinks:[{type:{name:'Blocks'},outwardIssue:{}}]}}],ts),/invalid link endpoint/);
console.log('Jira adapter formatter, direction, invalid input PASS');
